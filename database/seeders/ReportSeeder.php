  public function run(): void
  {
    DB::connection('sinkyu_massage_system_db')->statement('SET FOREIGN_KEY_CHECKS=0');
    DB::connection('sinkyu_massage_system_db')->table('reports')->truncate();
    DB::connection('sinkyu_massage_system_db')->statement('SET FOREIGN_KEY_CHECKS=1');

    // recordsが存在する（clinic_user_id, 年月）の組み合わせを取得
    $months = DB::connection('sinkyu_massage_system_db')
      ->table('records')
      ->selectRaw('clinic_user_id, DATE_FORMAT(date, "%Y-%m-01") as service_provide_month')
      ->groupBy('clinic_user_id', DB::raw('DATE_FORMAT(date, "%Y-%m-01")'))
      ->orderBy('clinic_user_id')
      ->orderBy(DB::raw('DATE_FORMAT(date, "%Y-%m-01")'))
      ->get();

    $rows = [];
    foreach ($months as $m) {
      $rows[] = [
        'clinic_user_id'              => $m->clinic_user_id,
        'service_provide_month'       => $m->service_provide_month,
        'subjective_symptom_and_wish' => $this->generateText($this->subjectivePhrases),
        'objective_symptom'           => $this->generateText($this->objectivePhrases),
        'therapy_content'             => $this->generateText($this->therapyContentPhrases),
        'therapy_plan'                => $this->generateText($this->therapyPlanPhrases),
      ];
    }

    // 200件ずつchunkしてinsert
    foreach (array_chunk($rows, 200) as $chunk) {
      DB::connection('sinkyu_massage_system_db')->table('reports')->insert($chunk);
    }

    $this->command->info('ReportSeeder: ' . count($rows) . '件挿入完了。');
  }

  /**
   * フレーズ配列からランダムに1~3文を選んで連結し、2~200字の文章を生成する。
   */
  private function generateText(array $phrases): string
  {
    shuffle($phrases);
    $count  = rand(1, 3);
    $selected = array_slice($phrases, 0, $count);
    $text   = implode('', $selected);

    // 200字を超える場合はmb_substrで切り詰め（文末が途中にならないよう句点で切る）
    if (mb_strlen($text) > 200) {
      $trimmed = mb_substr($text, 0, 200);
      // 直前の句点位置でカット
      $lastKuten = mb_strrpos($trimmed, '。');
      $text = ($lastKuten !== false && $lastKuten >= 2)
        ? mb_substr($trimmed, 0, $lastKuten + 1)
        : mb_substr($trimmed, 0, 200);
    }

    // 2字未満になった場合はフォールバック
    if (mb_strlen($text) < 2) {
      $text = $phrases[0];
    }

    return $text;
  }
